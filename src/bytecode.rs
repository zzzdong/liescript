/// 修改为三操作数指令格式：
/// +--------+--------+----+~~~~+~~~~+
/// | OPCODE |  FLAG  |RTRG|SRC1|SRC2|
/// +--------+--------+----+~~~~+~~~~+
/// |  1~255 |  1~255 |8bit|0~8B|0~8B|
/// +--------+--------+----+~~~~+~~~~+
pub struct Opcode {
    pub op: Op,
    /// FLAG字段：高4位用于指令功能分区，低4位表示源操作数类型
    /// 高4位（位4-7）：
    ///   [6-7]位：数据类型 (0b00=整型, 0b01=浮点, 0b10=字节)
    ///   [4-5]位：保留区域
    /// 低4位（位0-3）：
    ///   [0-1]位：src1类型 (0b00=无, 0b01=寄存器, 0b10=立即数, 0b11=内存地址)
    ///   [2-3]位：src2类型 (0b00=无, 0b01=寄存器, 0b10=立即数, 0b11=内存地址)
    /// 跳转指令(Br/BrIf)使用src1存储i64跳转偏移
    pub flag: u8,
    // 目标操作数只能是寄存器
    pub dst: u8,
    // 源操作数可以是寄存器或立即数
    pub src1: Operand,
    pub src2: Operand,
}

// 操作数类型枚举
pub enum Operand {
    None,        // 无操作数
    Reg(u8),     // 寄存器操作数
    Imm(u64),    // 无符号立即数操作数
    ImmI64(i64), // 有符号立即数操作数（用于跳转偏移）
}

// 简化后的操作码（通过flag区分数据类型）
pub enum Op {
    Add,  // 加法
    Sub,  // 减法
    Mul,  // 乘法
    Div,  // 除法
    Rem,  // 取余
    Or,   // 按位或
    And,  // 按位与
    Lsh,  // 左移
    Rsh,  // 右移
    Neg,  // 取负
    Mov,  // 数据移动
    Br,   // 跳转
    BrIf, // 条件跳转
}
